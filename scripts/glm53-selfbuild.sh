#!/usr/bin/env bash
# glm53-selfbuild.sh — build the upstream kernel-stack image chain on either Spark node.
# ONE multi-stage build (Reederey87 docs/10 chain): day-0 base -> v149 overlay (exllamav3
# v1.4.9 + fat GEMM + ticket scheduler + 10 core patches) -> e3 grouped fat-MoE ext -> W3
# zfill cubin -> task-42 f1s8 pipeline/reuse -> instanttensor (scitix, official vLLM
# extension). Produces only the final tag (default glm53-selfbuild:e3); per-stage recovery:
# --target glm53-base|e3-grouped|e3-cubin|e3-pipeline.
# The merged Dockerfile is regenerated each run from the kit's four Dockerfiles — instructions
# byte-identical to the originals so build cache hits; only ARG BASE/FROM plumbing becomes
# FROM <stage>. A trailing line-continuation on a section's last line is stripped in-stream:
# the buildkit parser SKIPS comment and empty/whitespace-only lines inside a \-continuation
# and JOINS the next real line, so an appended section's FROM would be swallowed (traced in
# moby/buildkit parser.go + tested 2026-09-22). A continuation at a section end is dangling
# by definition (the blank line ends the section), so stripping is always safe. Generated
# file removed on exit (kept in --check mode).
#
# RUN:  ssh sparkN 'bash -s' < ~/spark/glm53-selfbuild.sh     (builds on that node, ships to
#       the other; engine DOWN — nvcc wants >10GB host RAM, building while the engine is up
#       invites the GB10 UVM-livelock class; ~1.5-2.5h cold, ~instant on cache)
#       --check: generate + lint only, safe while the engine is up.
# NEW-BASE lane (upstream tag churns daily — resolve fresh, build under a NEW tag, A/B before
# adopting; overlay patches were written against the day-0 cut):
#   D=$(docker buildx imagetools inspect vllm/vllm-openai:glm53-flash-arm64-cu130 | awk '/^Digest:/{print $2; exit}')
#   ssh spark2 "BASE=vllm/vllm-openai:glm53-flash@\$D TAG=glm53-selfbuild:e3-nb bash -s" < ~/spark/glm53-selfbuild.sh
set -euo pipefail
BASE=${BASE:-vllm/vllm-openai:glm53-flash@sha256:905c02933be6021301db2dc284e24e3727467aa3a0f63b41d609885778a07bce}

KIT=$HOME/glm53-kit
# default TAG follows the staged state: e4 layer present -> e4 (the merged chain's last
# stage IS e4; tagging it e3 would mislabel patched content), absent -> e3 (plain chain)
TAG=${TAG:-$([ -f "$KIT/Dockerfile.e4-layer" ] && echo glm53-selfbuild:e4 || echo glm53-selfbuild:e3)}

for c in docker git ssh; do command -v "$c" >/dev/null || { echo "missing: $c"; exit 1; }; done
(( $(df --output=avail -BG / | tail -1 | tr -dc 0-9) >= 100 )) || { echo "need >=100G free on /"; exit 1; }

[ -d $KIT/.git ] || git clone --depth 50 https://github.com/Reederey87/glm53-flash-exl3-2x-dgx-spark "$KIT"
cd "$KIT"
STAMP=$(git rev-parse --short HEAD)

# --- merge the four kit Dockerfiles into one multi-stage file ---
DF=/tmp/Dockerfile.selfbuild-merged
: > "$DF"
printf '# GENERATED by glm53-selfbuild.sh — merged multi-stage chain from the kit Dockerfiles.\n# Per-stage recovery: --target glm53-base | e3-grouped | e3-cubin | e3-pipeline | e4.
# e4 lane (consolidation): when Dockerfile.e4-layer + bake.sh + mods/ are staged in the kit
# dir (~/spark/e4/stage-e4.sh ships them), the merged chain gains a final e4 stage that
# applies the adopted mod patches AT BUILD TIME (bake.sh, proven order, fail-closed);
# runtime gates stay in the recipe env. TAG=glm53-selfbuild:e4 then produces the
# consolidated image in ONE build.\n\n' > "$DF"
merge() { # $1=FROM-stage-line $2=kit-Dockerfile
  [ "$(grep -Fc 'ARG BASE=' "$2")" = 1 ] && [ "$(grep -Fxc 'FROM ${BASE}' "$2")" = 1 ] \
    || { echo "unexpected ARG BASE/FROM plumbing in $2"; exit 1; }
  # $s strips a dangling continuation on the section's last line (see header note)
  sed -e '/^ARG BASE=/d' -e "s|^FROM \${BASE}\$|$1|" -e '$s/\\[[:space:]]*$//' \
      "$2" | tail -n +2 >> "$DF"
  echo "" >> "$DF"
}
merge "FROM $BASE AS glm53-base" Dockerfile
merge "FROM glm53-base AS e3-grouped" Dockerfile.e3-layer
merge "FROM e3-grouped AS e3-cubin" Dockerfile.e3-cubin-layer
merge "FROM e3-cubin AS e3-pipeline" Dockerfile.e3-pipeline-layer
