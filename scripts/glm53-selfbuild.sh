FROM e3-pipeline AS e3-final
ARG GLM53_RECIPE_STAMP=unknown
ARG GLM53_EXL3_MOE_PIPELINE_FRAG=1
ARG GLM53_EXL3_MOE_PIPELINE_SH=8
